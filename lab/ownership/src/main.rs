// =============================================================================
// Rust 所有权机制演示
//
// 设计意图：
// Rust 的所有权系统是一种编译时资源管理机制。
// 核心问题：谁负责释放这个资源？什么时候释放？
// 传统语言用 GC 或手动管理，Rust 用类型系统在编译时确定。
//
// 对比 Java：所有对象都在堆上，GC 负责回收，释放时机不确定。
// 对比 Go：同样依赖 GC，但有更简单的内存模型。
// Rust 的方案：确定性析构 + 零运行时开销。
// =============================================================================

fn main() {
    println!("=== 所有权基础 ===\n");

    // -----------------------------------------------------------------------------
    // 1. Move 语义：所有权的转移
    // -----------------------------------------------------------------------------
    // 设计意图：为什么 s1 会无效？
    // - 每个值有且只有一个 owner
    // - 当 owner 被赋值给另一个变量，所有权发生转移（move）
    // - s1 在赋值后无效，编译器会阻止使用已移动的值
    //
    // 对比 Java：String s1 = new String("hello"); String s2 = s1;
    // Java 中 s1 和 s2 都指向同一个对象，s1 仍然有效
    // Java 需要 GC 来回收不再引用的对象，而 Rust 在 s2 离开作用域时立即释放
    //
    // 对比 Go：s1 := "hello"; s2 := s1
    // Go 中字符串不可变，s1 和 s2 共享底层数组，但仍然依赖 GC 回收

    let s1 = String::from("hello");
    println!("s1 创建：\"{}\"", s1);

    let s2 = s1; // s1 的所有权转移给 s2，s1 在此处无效
    // 如果 uncomment 下面这行，编译器报错：
    // println!("s1 = {}", s1); // error: use of moved value: `s1`

    println!("s2 接收所有权：\"{}\"", s2);
    println!("注释：s1 已无效（所有权转移），这在 Java/Go 中是不可能的\n");

    // s2 离开作用域时，String 被 drop，内存被释放
    // 这就是"确定性析构"——我们精确知道释放时机

    // -----------------------------------------------------------------------------
    // 2. Clone：显式深拷贝
    // -----------------------------------------------------------------------------
    // 设计意图：为什么要 .clone() 必须是显式的？
    // - 提醒开发者这是有代价的操作（堆内存分配）
    // - Java 中所有对象赋值都是隐式引用，克隆需要显式调用 .clone()
    // - Rust 把选择权给开发者：隐式 move 或显式 clone

    let s3 = String::from("world");
    let s4 = s3.clone(); // 显式深拷贝，s3 仍然有效

    println!("s3 = \"{}\", s4 = \"{}\" (clone)", s3, s4);
    println!("注释：显式克隆提醒我们这里有堆内存分配\n");

    // -----------------------------------------------------------------------------
    // 3. Copy trait：栈上类型的隐式拷贝
    // -----------------------------------------------------------------------------
    // 设计意图：为什么 i32 可以直接拷贝而不会"移动"？
    // - i32 是 Copy 类型，在栈上分配，大小固定
    // - 拷贝 i32 和拷贝指针不同——它没有任何堆内存引用
    // - Copy 类型赋值时是位复制（bitwise copy），原变量仍然有效
    //
    // Rust 的设计：能在栈上简单复制的类型自动实现 Copy trait，
    // 这样就不需要显式克隆，也不会引入所有权转移的复杂性。

    let x = 42;
    let y = x; // i32 实现了 Copy，所以 x 仍然有效

    println!("x = {}, y = {} (i32 is Copy)", x, y);
    println!("注释：Copy 类型赋值不转移所有权\n");

    // -----------------------------------------------------------------------------
    // 4. 函数参数的所有权
    // -----------------------------------------------------------------------------
    // 设计意图：所有权可以被函数"消费"
    // - 当值传递给函数时，所有权发生转移
    // - 函数负责在结束调用时 drop 这个值
    // - 这就是为什么 Rust 的函数签名需要 &（借用）如果你还想保留所有权

    // 注意：传递给函数时会转移所有权
    // consume(message);
    // println!("{}", message); // 编译错误！message 已转移
    //
    // 如果想在函数中使用但保留所有权，需要传递引用：
    // borrow(&message);

    println!("owned_by_function 函数演示（查看源码注释）\n");
    owned_by_function();

    // -----------------------------------------------------------------------------
    // 5. 借用（Borrowing）：使用值但不获取所有权
    // -----------------------------------------------------------------------------
    // 设计意图：借用解决了"使用但不拥有"的问题
    // - &T 表示不可变借用
    // - &mut T 表示可变借用
    // - 借用检查器确保借用不能比 owner 活得更久

    let text = String::from("hello rust");
    let len = calculate_length(&text); // 传递引用，借用但不拥有

    println!("\"{}\" 的长度是 {}", text, len);
    println!("注释：text 仍然有效，因为我们只借用了它\n");

    // -----------------------------------------------------------------------------
    // 6. 可变借用规则
    // -----------------------------------------------------------------------------
    // 设计意图：为什么可变借用是独占的？
    // - 同时存在多个可变借用会导致数据竞争（data race）
    // - 借用检查器在编译时就防止了这种情况
    // - 对比：Java 的 synchronized 是在运行时检查，Go 的 channel 也是运行时调度

    let mut s = String::from("hello");

    let r1 = &s; // 第一个不可变借用
    let r2 = &s; // 第二个不可变借用 OK（多个不可变借用是安全的）
    println!("r1 = {}, r2 = {}", r1, r2);
    // r1 和 r2 在此处之后不再使用

    let r3 = &mut s; // 可变借用 OK，因为 r1, r2 已不再使用
    // 借用检查器使用 NLL（Non-Lexical Lifetimes），只追踪实际使用范围
    println!("r3 = {}", r3);
    println!("注释：可变借用是独占的，但不可变借用可以多个共存\n");

    // -----------------------------------------------------------------------------
    // 7. 垂悬引用（悬空指针）检查
    // -----------------------------------------------------------------------------
    // 设计意图：Rust 在编译时就防止了垂悬指针
    // - 垂悬指针：指向已释放内存的指针
    // - C/C++ 的经典 bug，Java/Go 的 GC 可以防止（但有代价）
    // - Rust 的生命周期检查确保引用不能比它指向的值活得更久

    // 下面这段代码如果 uncomment 会编译失败：
    // let dangling = dangle();
    // fn dangle() -> &String { // 编译错误！
    //     let s = String::from("hello");
    //     &s // 返回对 s 的引用，但 s 在函数结束时被 drop
    // }

    println!("dangle 函数演示（查看源码注释）：垂悬引用在编译时被检测\n");

    // -----------------------------------------------------------------------------
    // 8. 所有者与生命周期
    // -----------------------------------------------------------------------------
    // 设计意图：生命周期（Lifetime）是借用检查的核心
    // - 每个引用都有一个生命周期，标识它有效的范围
    // - 生命周期注解用于告诉编译器多个引用的相对关系
    //
    // Rust 的生命周期省略规则：
    // - 每个输入引用参数获得自己的生命周期
    // - 如果只有一个输入生命周期，它被赋给所有输出引用

    let novel = String::from("The Rust Programming Language");
    let first = first_word(&novel);
    println!("第一个单词：{}", first);

    let s1 = String::from("hello");
    let result = longest(&s1, &s1); // 生命周期演示
    println!("较长的字符串：{}", result);

    println!("\n=== 设计启示 ===\n");
    println!("1. 所有权转移 = 线性类型的资源管理");
    println!("2. 确定性析构 = 编译时确定释放时机，无 GC 暂停");
    println!("3. 借用检查 = 编译时防止数据竞争和垂悬指针");
    println!("4. Copy trait = 栈上类型的零开销复制");
    println!("\n对比 Java：GC 提供安全性但牺牲了确定性和性能");
    println!("对比 Go：更简单的模型但同样依赖 GC，nil 指针仍然存在");
}

// -----------------------------------------------------------------------------
// 演示：函数获取所有权
// -----------------------------------------------------------------------------
fn owned_by_function() {
    // 这个函数获取 text 的所有权
    fn consume(s: String) {
        println!("consumed: {}", s);
    } // s 在这里被 drop

    let text = String::from("owned");
    consume(text);
    // text 在这里已经无效，不能再使用
    println!("注释：text 的所有权已被 consume 函数消费\n");
}

// -----------------------------------------------------------------------------
// 演示：借用但不获取所有权
// -----------------------------------------------------------------------------
fn calculate_length(s: &String) -> usize {
    s.len()
} // s 是借用，不影响原值的所有权

// -----------------------------------------------------------------------------
// 演示：生命周期注解
// -----------------------------------------------------------------------------
// 设计意图：生命周期注解描述引用的存在时间关系
// 'a 表示"some lifetime a"，告诉编译器返回的引用和输入的引用有相同有效性
//
// 为什么需要这个注解？
// longest 函数返回两个引用中较长的那个
// 编译器需要知道返回的引用不会在输入引用被 drop 之后仍然存在

fn longest<'a>(s1: &'a str, s2: &'a str) -> &'a str {
    if s1.len() > s2.len() {
        s1
    } else {
        s2
    }
}

// -----------------------------------------------------------------------------
// 演示：垂悬引用（编译错误）
// -----------------------------------------------------------------------------
// 这个函数会返回一个指向局部变量的引用
// fn dangle() -> &String {
//     let s = String::from("hello");
//     &s // 错误：s 在函数结束时被 drop，返回的引用指向已释放的内存
// }
//
// Rust 的生命周期规则：
// - 如果函数返回引用，返回生命周期必须与某个输入参数关联
// - 编译器确保返回的引用不会 outlive 它指向的值

fn first_word(s: &str) -> &str {
    let bytes = s.as_bytes();
    for (i, &byte) in bytes.iter().enumerate() {
        if byte == b' ' {
            return &s[0..i];
        }
    }
    s
}
